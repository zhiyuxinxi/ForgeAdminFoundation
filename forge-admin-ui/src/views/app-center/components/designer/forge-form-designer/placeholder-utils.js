export function isChoicePlaceholderComponent(componentKey = '') {
  return CHOICE_PLACEHOLDER_COMPONENTS.has(String(componentKey || '').toLowerCase())
}

export function buildDefaultPlaceholder(componentKey = '', label = '') {
  const cleanLabel = String(label || '').trim()
  const prefix = isChoicePlaceholderComponent(componentKey) ? '请选择' : '请填写'
  return cleanLabel ? `${prefix}${cleanLabel}` : prefix
}

export function shouldSyncPlaceholder(component = {}) {
  const currentPlaceholder = component.props?.placeholder
  if (currentPlaceholder === undefined || currentPlaceholder === null)
    return true
  const currentText = String(currentPlaceholder).trim()
  if (!currentText)
    return true
  return isAutoGeneratedPlaceholder(component, currentText)
}

export function buildFieldAssetPlaceholderPatch(component = {}, payload = {}) {
  const hasPlaceholder = Object.prototype.hasOwnProperty.call(payload, 'placeholder')
  const incomingPlaceholder = hasPlaceholder ? String(payload.placeholder || '') : ''
  const currentPlaceholder = String(component.props?.placeholder || '')
  if (hasPlaceholder && incomingPlaceholder !== currentPlaceholder)
    return { placeholder: incomingPlaceholder }
  if (Object.prototype.hasOwnProperty.call(payload, 'fieldName') && shouldSyncPlaceholder(component)) {
    return {
      placeholder: buildDefaultPlaceholder(component.componentKey, payload.fieldName),
    }
  }
  return hasPlaceholder ? { placeholder: incomingPlaceholder } : {}
}

function isAutoGeneratedPlaceholder(component = {}, placeholder = '') {
  const text = String(placeholder || '').trim()
  if (!text)
    return true
  return resolveAutoPlaceholderLabels(component)
    .some(label => buildAutoPlaceholderCandidates(component.componentKey, label).includes(text))
}

function buildAutoPlaceholderCandidates(componentKey = '', label = '') {
  const cleanLabel = String(label || '').trim()
  const prefixes = isChoicePlaceholderComponent(componentKey)
    ? ['请选择']
    : ['请填写', '请输入', '请填入']
  return prefixes.map(prefix => cleanLabel ? `${prefix}${cleanLabel}` : prefix)
}

function resolveAutoPlaceholderLabels(component = {}) {
  const labels = [
    component.label,
    component.props?.label,
    component.props?.title,
    component.props?.header,
    component.fieldBinding?.fieldName,
    component.fieldBinding?.fieldCode,
    component.field,
    component.name,
    COMPONENT_DEFAULT_LABELS[component.componentKey],
    '字段',
  ]
  return Array.from(new Set(labels.map(label => String(label || '').trim()).filter(Boolean)))
}
