// BPMN library chrome only: business object names and XML remain untouched.
export function translateBpmn(template, replacements = {}) {
  const text = getLocale() === 'zh-CN' ? (chineseLabels[template] || template) : template
  return text.replace(/\{([^}]+)\}/g, (match, key) => Object.hasOwn(replacements, key) ? String(replacements[key]) : match)
}

export default { translate: ['value', translateBpmn] }
