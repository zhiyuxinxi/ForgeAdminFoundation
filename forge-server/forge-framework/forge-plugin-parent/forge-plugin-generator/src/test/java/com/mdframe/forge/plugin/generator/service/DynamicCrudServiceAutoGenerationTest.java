package com.mdframe.forge.plugin.generator.service;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.mdframe.forge.plugin.generator.service.runtime.value.RuntimeFieldMetadata;
import com.mdframe.forge.plugin.generator.service.runtime.write.RuntimeAutoGeneration;
import com.mdframe.forge.plugin.generator.service.runtime.write.RuntimeEditFieldReader;
import com.mdframe.forge.plugin.generator.service.runtime.write.RuntimeGenerationRules;
import com.mdframe.forge.plugin.generator.service.runtime.write.RuntimeWriteFieldMapping;
import com.mdframe.forge.lowcode.api.config.LowcodeRuntimeConfig;
import com.mdframe.forge.plugin.generator.dto.DynamicCrudQuery;
import com.mdframe.forge.plugin.generator.service.businessapp.CodeRuleService;
import com.mdframe.forge.plugin.generator.service.runtime.query.RuntimeSearchFields;
import com.mdframe.forge.plugin.generator.service.runtime.query.RuntimeSearchTreeSource;
import com.mdframe.forge.plugin.generator.service.runtime.tree.RuntimeTreeConfigResolver;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.Map;
import java.util.Set;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

@DisplayName("DynamicCrudService auto generation")
class DynamicCrudServiceAutoGenerationTest {

    private final FakeDynamicCrudRepository repository = new FakeDynamicCrudRepository();
    private final FakeCodeRuleService codeRuleService = new FakeCodeRuleService();
    private final ObjectMapper objectMapper = new ObjectMapper();
    private final RuntimeSearchFields searchFields = new RuntimeSearchFields(objectMapper,
            new RuntimeSearchTreeSource(objectMapper, new RuntimeTreeConfigResolver(objectMapper)));

    @Test
    @DisplayName("generates conventional code field when explicit generation config is absent")
    void generatesConventionalCodeFieldWhenGenerationConfigAbsent() throws Exception {
        LowcodeRuntimeConfig config = materialConfig();
        repository.setColumnMapping(Map.of(
                "materialCode", "material_code",
                "material_code", "material_code",
                "materialName", "material_name",
                "material_name", "material_name"
        ));
        codeRuleService.setGeneratedCode("material_code", "WL00001");
        Map<String, Object> data = new LinkedHashMap<>();
        data.put("materialCode", null);
        data.put("materialName", "水泥");
        Set<String> allowedFields = new LinkedHashSet<>(Set.of("materialCode", "materialName"));

        applyAutoGeneratedFields(config, data, allowedFields);

        assertEquals("WL00001", data.get("materialCode"));
        assertEquals("WL00001", data.get("material_code"));
        assertTrue(allowedFields.contains("materialCode"));
        assertTrue(allowedFields.contains("material_code"));
        assertEquals("material_code", codeRuleService.getLastRuleCode());
        assertEquals("水泥", ((Map<?, ?>) codeRuleService.getLastContext().get("fields")).get("materialName"));
        assertEquals("PW_MATERIAL", ((Map<?, ?>) codeRuleService.getLastContext().get("fields")).get("objectCode"));
        assertNull(codeRuleService.getLastContext().get("tenantId"));
    }

    @Test
    @DisplayName("keeps user entered code for empty-only conventional field")
    void keepsUserEnteredCodeForEmptyOnlyConventionalField() throws Exception {
        LowcodeRuntimeConfig config = materialConfig();
        repository.setColumnMapping(Map.of(
                "materialCode", "material_code",
                "material_code", "material_code"
        ));
        Map<String, Object> data = new LinkedHashMap<>();
        data.put("materialCode", "CUSTOM-001");

        applyAutoGeneratedFields(config, data, new LinkedHashSet<>());

        assertEquals("CUSTOM-001", data.get("materialCode"));
        assertEquals(0, codeRuleService.getGenerateCalls());
    }

    @Test
    @DisplayName("allows page-level search fields already exposed by list or edit schemas")
    void allowsPageLevelSearchFieldsFromRuntimeSchemas() throws Exception {
        LowcodeRuntimeConfig config = materialConfig();
        config.setSearchSchema("""
                [{"field":"id","type":"number","queryType":"eq"}]
                """);
        config.setColumnsSchema("""
                [{"prop":"customerName","title":"客户名称"}]
                """);
        config.setEditSchema("""
                [{"field":"amount","label":"金额","type":"number"}]
                """);

        Set<String> allowedFields = searchFields.search(config);

        assertTrue(allowedFields.contains("id"));
        assertTrue(allowedFields.contains("customerName"));
        assertTrue(allowedFields.contains("amount"));
    }

    @Test
    @DisplayName("accepts only supported page-level query operator overrides")
    void acceptsOnlySupportedPageSearchTypeOverrides() throws Exception {
        LowcodeRuntimeConfig config = materialConfig();
        config.setSearchSchema("""
                [{"field":"id","type":"number","queryType":"eq"}]
                """);
        DynamicCrudQuery query = new DynamicCrudQuery();
        query.setSearchTypeMap(Map.of(
                "customerName", "like",
                "amount", "drop table"
        ));

        Map<String, String> searchTypes = searchFields.types(config, query, Set.of("id", "customerName", "amount"));

        assertEquals("eq", searchTypes.get("id"));
        assertEquals("like", searchTypes.get("customerName"));
        assertNull(searchTypes.get("amount"));
    }

    @Test
    @DisplayName("does not apply conventional fallback when generation is explicitly configured")
    void doesNotApplyFallbackWhenGenerationExplicitlyConfigured() throws Exception {
        LowcodeRuntimeConfig config = materialConfigWithDisabledGeneration();
        repository.setColumnMapping(Map.of(
                "materialCode", "material_code",
                "material_code", "material_code"
        ));
        codeRuleService.setGeneratedCode("material_code", "WL00001");
        Map<String, Object> data = new LinkedHashMap<>();
        data.put("materialCode", null);

        applyAutoGeneratedFields(config, data, new LinkedHashSet<>());

        assertNull(data.get("materialCode"));
        assertEquals(0, codeRuleService.getGenerateCalls());
    }

    private void applyAutoGeneratedFields(LowcodeRuntimeConfig config,
                                          Map<String, Object> data,
                                          Set<String> allowedFields) throws Exception {
        RuntimeFieldMetadata metadata = new RuntimeFieldMetadata(objectMapper);
        RuntimeAutoGeneration generation = new RuntimeAutoGeneration(
                new RuntimeGenerationRules(metadata, new RuntimeEditFieldReader(objectMapper)),
                new RuntimeWriteFieldMapping(repository, metadata), codeRuleService, null);
        generation.apply(config, data, allowedFields);
    }

    private LowcodeRuntimeConfig materialConfig() {
        LowcodeRuntimeConfig config = new LowcodeRuntimeConfig();
        config.setTenantId(1L);
        config.setConfigKey("pw_material");
        config.setObjectCode("PW_MATERIAL");
        config.setTableName("pw_material");
        config.setModelSchema("""
                {
                  "tableName": "pw_material",
                  "fields": [
                    {
                      "field": "materialCode",
                      "columnName": "material_code",
                      "label": "物料编号",
                      "dataType": "varchar",
                      "length": 64,
                      "required": true
                    },
                    {
                      "field": "materialName",
                      "columnName": "material_name",
                      "label": "物料名称",
                      "dataType": "varchar",
                      "length": 128,
                      "required": true
                    }
                  ]
                }
                """);
        config.setEditSchema("""
                [
                  {"field": "materialCode", "label": "物料编号", "type": "input"},
                  {"field": "materialName", "label": "物料名称", "type": "input"}
                ]
                """);
        return config;
    }

    private LowcodeRuntimeConfig materialConfigWithDisabledGeneration() {
        LowcodeRuntimeConfig config = materialConfig();
        config.setModelSchema("""
                {
                  "tableName": "pw_material",
                  "fields": [
                    {
                      "field": "materialCode",
                      "columnName": "material_code",
                      "label": "物料编号",
                      "dataType": "varchar",
                      "length": 64,
                      "required": true,
                      "basicProps": {
                        "generation": {
                          "enabled": false,
                          "ruleCode": "material_code"
                        }
                      }
                    }
                  ]
                }
                """);
        return config;
    }

    private static class FakeDynamicCrudRepository extends DynamicCrudRepository {

        private Map<String, String> columnMapping = Map.of();

        FakeDynamicCrudRepository() {
            super(null, null, null);
        }

        void setColumnMapping(Map<String, String> columnMapping) {
            this.columnMapping = columnMapping;
        }

        @Override
        public Map<String, String> getColumnMapping(String tableName) {
            return columnMapping;
        }
    }

    private static class FakeCodeRuleService extends CodeRuleService {

        private final Map<String, String> generatedCodes = new LinkedHashMap<>();
        private int generateCalls;
        private String lastRuleCode;
        private Map<String, Object> lastContext;

        FakeCodeRuleService() {
            super(null, null, null);
        }

        void setGeneratedCode(String ruleCode, String generatedCode) {
            generatedCodes.put(ruleCode, generatedCode);
        }

        int getGenerateCalls() {
            return generateCalls;
        }

        String getLastRuleCode() {
            return lastRuleCode;
        }

        Map<String, Object> getLastContext() {
            return lastContext;
        }

        @Override
        public String generate(String ruleCode, Map<String, Object> context) {
            generateCalls++;
            lastRuleCode = ruleCode;
            lastContext = context;
            return generatedCodes.get(ruleCode);
        }
    }
}
