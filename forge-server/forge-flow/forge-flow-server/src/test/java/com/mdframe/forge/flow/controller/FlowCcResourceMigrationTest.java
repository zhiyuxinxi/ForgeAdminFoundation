package com.mdframe.forge.flow.controller;

import org.junit.jupiter.api.Test;

import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.Statement;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;

class FlowCcResourceMigrationTest {
    @Test
    void registersIdempotentEndpointsAndPreservesOnlyExistingRecipientGrants() throws Exception {
        try (Connection connection = DriverManager.getConnection(
                "jdbc:h2:mem:cc-migration-" + UUID.randomUUID() + ";MODE=MySQL", "sa", "");
             Statement sql = connection.createStatement()) {
            sql.execute("CREATE TABLE sys_resource (id BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1000) PRIMARY KEY, "
                    + "tenant_id BIGINT, resource_name VARCHAR(100), resource_name_en VARCHAR(100), parent_id BIGINT, "
                    + "resource_type INT, sort INT, is_external INT, sso_enabled INT, open_target VARCHAR(20), "
                    + "is_public INT, menu_status INT, visible INT, perms VARCHAR(100), api_method VARCHAR(20), "
                    + "api_url VARCHAR(255), keep_alive INT, always_show INT, remark VARCHAR(255), create_by BIGINT, "
                    + "create_time TIMESTAMP, update_by BIGINT, update_time TIMESTAMP, create_dept BIGINT, "
                    + "client_code VARCHAR(20), path VARCHAR(100), del_flag BIGINT DEFAULT 0)");
            sql.execute("CREATE TABLE sys_role (id BIGINT PRIMARY KEY, tenant_id BIGINT, role_status INT, del_flag BIGINT)");
            sql.execute("CREATE TABLE sys_role_resource (tenant_id BIGINT, role_id BIGINT, resource_id BIGINT, create_time TIMESTAMP)");
            sql.execute("INSERT INTO sys_resource (id,tenant_id,resource_type,path,client_code) "
                    + "VALUES (10,1,2,'/flow/cc','pc'),(20,2,2,'/flow/cc','pc')");
            sql.execute("INSERT INTO sys_role VALUES (7,1,1,0),(8,2,1,0),(9,1,1,0)");
            sql.execute("INSERT INTO sys_role_resource (tenant_id,role_id,resource_id) "
                    + "VALUES (1,7,10),(2,8,20),(1,8,10)");

            Path migration = Path.of("../../db/migration/V1.0.2026101901__secure_flow_cc_resources.sql");
            String script = Files.readString(migration).replaceAll("(?m)^--.*$", "");
            for (int run = 0; run < 2; run++) {
                for (String statement : script.split(";")) {
                    if (!statement.isBlank()) sql.execute(statement);
                }
            }

            assertThat(count(sql, "SELECT COUNT(*) FROM sys_resource WHERE resource_type=4")).isEqualTo(16);
            assertThat(count(sql, "SELECT COUNT(*) FROM sys_role_resource g JOIN sys_resource r ON r.id=g.resource_id "
                    + "WHERE r.resource_type=4 AND g.tenant_id=1 AND g.role_id=7")).isEqualTo(6);
            assertThat(count(sql, "SELECT COUNT(*) FROM sys_role_resource g JOIN sys_resource r ON r.id=g.resource_id "
                    + "WHERE r.resource_type=4 AND g.tenant_id=2 AND g.role_id=8")).isEqualTo(6);
            assertThat(count(sql, "SELECT COUNT(*) FROM sys_role_resource g JOIN sys_resource r ON r.id=g.resource_id "
                    + "WHERE r.resource_type=4 AND (r.tenant_id<>g.tenant_id OR g.role_id=9 "
                    + "OR (g.tenant_id=1 AND g.role_id=8) OR r.perms IN ('flow:cc:send','flow:cc:sent'))")).isZero();
        }
    }

    private long count(Statement sql, String query) throws Exception {
        try (var rows = sql.executeQuery(query)) {
            rows.next();
            return rows.getLong(1);
        }
    }
}
